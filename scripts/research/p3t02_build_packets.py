# --------------------------------------------------------------------------- normalisation

def light_norm(text) -> str:
    """NFC, zero-width removed, Thai digits to Arabic, whitespace collapsed. Keeps punctuation (for cue rules)."""
    t = unicodedata.normalize("NFC", text or "").translate(ZERO_WIDTH).translate(THAI_DIGITS)
    return re.sub(r"\s+", " ", t).strip()


def normalise(text, thai_normalize=None) -> str:
    """Comparison form: light_norm, optional PyThaiNLP normalize, casefold, drop whitespace/punctuation/control."""
    t = light_norm(text)
    if thai_normalize is not None:
        t = thai_normalize(t)
    t = t.casefold()
    return "".join(ch for ch in t if unicodedata.category(ch)[0] not in "ZPC")


def norm_section(section) -> str:
    t = light_norm(section)
    return re.sub(r"^มาตรา\s*", "", t)


def source_id(law_code, section) -> str:
    return f"{law_code}/{norm_section(section)}"



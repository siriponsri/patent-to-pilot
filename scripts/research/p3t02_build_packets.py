def _ctx_list(value):
    return [c for c in (value or []) if c and c.get("metadata")]


def build(rows: dict, prov: dict, thai_normalize=None, params=None) -> dict:
    """Pure build over in-memory rows. ``rows`` keys: wangchanx, niti_ccl, niti_tax, statute, gazette_queries and
    optionally niti_ccl_copy. ``prov`` maps the same keys to {repo, revision, license, file}."""
    p = dict(DECLARED if params is None else params)
    k, thr, report = p["shingle_k"], p["variant_jaccard"], p["report_thresholds"]

    def norm(t):
        return normalise(t, thai_normalize)

    # statute corpus
    statute = {}
    name_to_code = {}
    for r in rows["statute"]:
        sid = source_id(r["law_code"], r["section_num"])
        refs = [x for x in (r.get("reference") or []) if x]
        statute[sid] = {"law_code": r["law_code"], "law_name": r.get("law_name"), "section_num": r["section_num"],
                        "id_section": norm_section(r["section_num"]), "text": r.get("section_content") or "",
                        "has_reference": any(x.get("include") for x in refs), "references": refs}
        if r.get("law_name"):
            name_to_code.setdefault(light_norm(r["law_name"]), r["law_code"])
    statute_laws = sorted({v["law_code"] for v in statute.values()})

    def law_of_name(name):
        code = name_to_code.get(light_norm(name))
        return code if code else "unmapped:" + sha256_text(light_norm(name))[:12]

    # held-out items and laws
    heldout_items, heldout_laws, ref_only_laws, unmapped_mentions = [], set(), set(), 0
    for split in ("ccl", "tax"):
        pv = prov[f"niti_{split}"]
        for i, r in enumerate(rows[f"niti_{split}"]):
            gold = []
            for law in r.get("relevant_laws") or []:
                code = law_of_name(law.get("law_name"))
                unmapped_mentions += code.startswith("unmapped:")
                gold.append({"law_code": code, "section": law.get("section_num"),
                             "source_id": source_id(code, law.get("section_num")), "text": law.get("section_content")})
            rel_laws = {g["law_code"] for g in gold}
            heldout_laws |= rel_laws
            for law in r.get("reference_laws") or []:
                code = law_of_name(law.get("law_name"))
                if code not in rel_laws:
                    ref_only_laws.add(code)
                heldout_laws.add(code)
            locator = f"{split}[{i}]"
            heldout_items.append({"split_name": split, "locator": locator, "question": r.get("question") or "",
                                  "gold": gold, "hash": record_hash(pv["repo"], pv["revision"], locator)})
    ref_only_laws -= {g["law_code"] for it in heldout_items for g in it["gold"]}

    # WangchanX train records
    pw = prov["wangchanx"]
    wx = []
    for i, r in enumerate(rows["wangchanx"]):
        pos = _ctx_list(r.get("positive_contexts"))
        neg = _ctx_list(r.get("hard_negative_contexts"))
        locator = f"train[{i}]"
        wx.append({"locator": locator, "hash": record_hash(pw["repo"], pw["revision"], locator),
                   "question": r.get("question") or "",
                   "pos": [{"law_code": c["metadata"]["law_code"], "section": c["metadata"]["section"],
                            "source_id": source_id(c["metadata"]["law_code"], c["metadata"]["section"]),
                            "context": c.get("context") or ""} for c in pos],
                   "neg": [{"law_code": c["metadata"]["law_code"],
                            "source_id": source_id(c["metadata"]["law_code"], c["metadata"]["section"])} for c in neg]})

    # normalised questions and shingles
    for it in wx + heldout_items:
        it["norm"] = norm(it["question"])
        it["sh"] = shingles(it["norm"], k)
    gz_raw = [q or "" for q in rows.get("gazette_queries", [])]
    gz_norm = [norm(q) for q in gz_raw]
    gz_sh = [shingles(x, k) for x in gz_norm]

    # ------------------------------------------------------------------ overlap audit (aggregates)
    audit = {"declared": p}
    wx_raw = [x["question"] for x in wx]
    wx_norm = [x["norm"] for x in wx]
    wx_sh = [x["sh"] for x in wx]
    wx_pos_sections = {g["source_id"] for x in wx for g in x["pos"]}
    wx_pos_laws = {g["law_code"] for x in wx for g in x["pos"]}
    heldout_max = [0.0] * len(wx)
    for split in ("ccl", "tax"):
        items = [x for x in heldout_items if x["split_name"] == split]
        q, a_max, b_max, b_arg = question_overlap(wx_raw, [x["question"] for x in items], wx_norm,
                                                  [x["norm"] for x in items], wx_sh, [x["sh"] for x in items], report)
        heldout_max = [max(a, float(b)) for a, b in zip(heldout_max, a_max)]
        gold_sections = {g["source_id"] for x in items for g in x["gold"]}
        gold_laws = {g["law_code"] for x in items for g in x["gold"]}
        near_same_section = 0
        for j, x in enumerate(items):
            if b_max[j] >= thr and b_arg[j] >= 0:
                if {g["source_id"] for g in x["gold"]} & {g["source_id"] for g in wx[int(b_arg[j])]["pos"]}:
                    near_same_section += 1
        q["sources"] = {
            "laws_a": len(wx_pos_laws), "laws_b": len(gold_laws), "laws_shared": len(wx_pos_laws & gold_laws),
            "sections_a": len(wx_pos_sections), "sections_b": len(gold_sections),
            "sections_shared": len(wx_pos_sections & gold_sections),
            "b_items_any_gold_section_in_a": sum(1 for x in items if {g["source_id"] for g in x["gold"]} & wx_pos_sections),
            "b_items_all_gold_sections_in_a": sum(1 for x in items
                                                  if x["gold"] and {g["source_id"] for g in x["gold"]} <= wx_pos_sections),
            "a_records_any_positive_in_b_gold": sum(1 for x in wx if {g["source_id"] for g in x["pos"]} & gold_sections),
            f"b_items_near_dup_{thr}_with_shared_gold_section": near_same_section,
        }
        audit[f"wangchanx_train_vs_nitibench_{split}"] = q
    if gz_raw:
        q, a_max, _, _ = question_overlap(wx_raw, gz_raw, wx_norm, gz_norm, wx_sh, gz_sh, report)
        heldout_max = [max(a, float(b)) for a, b in zip(heldout_max, a_max)]
        q["sources"] = "not comparable: Gazette evidence is notice ids, not statute sections; qrels not read"
        audit["wangchanx_train_vs_gazette_queries"] = q
    # within WangchanX train
    _, _, _, wx_pairs = jaccard_scan(wx_sh, pair_threshold=thr)
    norm_counts = collections.Counter(x for x in wx_norm if x)
    audit["wangchanx_train_internal"] = {
        "n": len(wx), "normalised_duplicate_groups": sum(1 for c in norm_counts.values() if c > 1),
        "records_in_normalised_duplicate_groups": sum(c for c in norm_counts.values() if c > 1),
        f"near_dup_pairs_{thr}": len(wx_pairs),
        f"records_in_near_dup_pairs_{thr}": len({i for pr in wx_pairs for i in pr}),
    }
    if rows.get("niti_ccl_copy") is not None:
        a = [r.get("question") or "" for r in rows["niti_ccl"]]
        b = [r.get("question") or "" for r in rows["niti_ccl_copy"]]
        audit["nitibench_ccl_config_vs_noncfg_copy"] = {
            "n_config": len(a), "n_copy": len(b),
            "positional_raw_differences": sum(1 for x, y in zip(a, b) if x != y) + abs(len(a) - len(b)),
            "normalised_multiset_equal": sorted(norm(x) for x in a) == sorted(norm(x) for x in b),
            "raw_multiset_equal": sorted(a) == sorted(b),
        }

    # ------------------------------------------------------------------ DEV eligibility
    heldout_norm = {x["norm"] for x in heldout_items if x["norm"]} | {x for x in gz_norm if x}
    excluded, dev = [], []
    reasons = collections.Counter({"no_positive_judgment": 0, "heldout_family_quarantine": 0, "empty_question": 0,
                                   "heldout_variant": 0})
    for i, x in enumerate(wx):
        if not x["pos"]:
            reason = "no_positive_judgment"
        elif {g["law_code"] for g in x["pos"]} & heldout_laws:
            reason = "heldout_family_quarantine"
        elif not x["norm"]:
            reason = "empty_question"
        elif x["norm"] in heldout_norm or heldout_max[i] >= thr:
            reason = "heldout_variant"
        else:
            reason = None
        if reason:
            reasons[reason] += 1
            excluded.append({"record_id_hash": x["hash"], "locator": x["locator"], "reason": reason})
        else:
            dev.append(x)

    # Families: one per law. An item joins the family of its primary (rank-1) gold law; DEV variant questions are
    # merged into the family of the variant group's first item (by record hash).
    dev_laws_all = sorted({law for law in statute_laws if law not in heldout_laws})
    dev_fam = {law: law_family("dev", law) for law in dev_laws_all}
    ho_fam = {law: law_family("heldout", law) for law in sorted(heldout_laws)}
    _, _, _, dev_pairs = jaccard_scan([x["sh"] for x in dev], pair_threshold=thr)
    vuf = UnionFind()
    for x in dev:
        vuf.add(x["hash"])
    for i, j in dev_pairs:
        vuf.union(dev[i]["hash"], dev[j]["hash"])
    primary = {x["hash"]: x["pos"][0]["law_code"] for x in dev}
    for x in heldout_items:
        primary[x["hash"]] = x["gold"][0]["law_code"] if x["gold"] else "no-gold"
    item_fam = {x["hash"]: dev_fam[primary[vuf.find(x["hash"])]] for x in dev}
    for x in heldout_items:
        ho_fam.setdefault(primary[x["hash"]], law_family("heldout", primary[x["hash"]]))
        item_fam[x["hash"]] = ho_fam[primary[x["hash"]]]
    audit["family_components"] = {
        "dev": component_sizes([[g["law_code"] for g in x["pos"]] for x in dev], dev_laws_all),
        "heldout": component_sizes([[g["law_code"] for g in x["gold"]] for x in heldout_items], sorted(heldout_laws)),
        "note": "items per connected component of laws linked by one item's gold; packets use one law per family",
    }

    def _prov(key, locator, rhash):
        pv = prov[key]
        return {"dataset": pv["repo"], "revision": pv["revision"], "license": pv["license"], "file": pv["file"],
                "locator": locator, "record_id_hash": rhash}

    out = {"dev": collections.defaultdict(list), "heldout": collections.defaultdict(list)}
    dropped_neg = 0
    extra_sources = {}
    for x in sorted(dev, key=lambda r: r["hash"]):
        fid = item_fam[x["hash"]]
        item_id = "wx-" + x["hash"][:16]
        label, q_origin = QUESTION_ORIGIN["wangchanx"]
        out["dev"]["requests"].append({
            "item_id": item_id, "packet_id": fid, "split": "dev", "question": x["question"],
            "question_sha256": sha256_text(x["question"]), "synthetic_label": label, "question_origin": q_origin,
            "provenance": _prov("wangchanx", x["locator"], x["hash"])})
        relevant, tag_sources = [], []
        for rank, g in enumerate(x["pos"], 1):
            in_corpus = g["source_id"] in statute
            src = statute.get(g["source_id"])
            if src is None:
                extra_sources.setdefault(g["source_id"], {"law_code": g["law_code"], "section_num": g["section"],
                                                          "text": g["context"],
                                                          "packet_id": dev_fam[g["law_code"]]})
                src = {"id_section": norm_section(g["section"]), "text": g["context"], "has_reference": False}
            relevant.append({"source_id": g["source_id"], "rank": rank, "in_statute_corpus": in_corpus,
                             "context_sha256": sha256_text(g["context"]),
                             "context_equals_statute": bool(in_corpus and g["context"].strip()
                                                            == statute[g["source_id"]]["text"].strip())})
            tag_sources.append(src)
        nonrel = []
        for g in x["neg"]:
            if g["law_code"] in heldout_laws:
                dropped_neg += 1
            elif g["source_id"] not in nonrel:
                nonrel.append(g["source_id"])
        out["dev"]["judgments"].append({
            "item_id": item_id, "packet_id": fid, "relevant": relevant, "judged_nonrelevant": nonrel,
            "gold_laws_in_other_packets": len({g["law_code"] for g in x["pos"]} - {primary[vuf.find(x["hash"])]}),
            "judgment_origin": JUDGMENT_ORIGIN["wangchanx"], "pooling": POOLING["wangchanx"],
            "independent_of_tested_policy": True, "task_types": tag_task_types(x["question"], tag_sources)})

    for x in sorted(heldout_items, key=lambda r: r["hash"]):
        fid = item_fam[x["hash"]]
        split = x["split_name"]
        item_id = f"nb{split}-" + x["hash"][:16]
        label, q_origin = QUESTION_ORIGIN[split]
        out["heldout"]["requests"].append({
            "item_id": item_id, "packet_id": fid, "split": "heldout", "question": x["question"],
            "question_sha256": sha256_text(x["question"]), "synthetic_label": label, "question_origin": q_origin,
            "provenance": _prov(f"niti_{split}", x["locator"], x["hash"])})
        tag_sources = [statute.get(g["source_id"]) or {"id_section": norm_section(g["section"]), "text": g["text"],
                                                        "has_reference": False} for g in x["gold"]]
        out["heldout"]["judgments"].append({
            "item_id": item_id, "packet_id": fid,
            "gold_laws_in_other_packets": len({g["law_code"] for g in x["gold"]} - {primary[x["hash"]]}),
            "relevant": [{"source_id": g["source_id"], "in_statute_corpus": g["source_id"] in statute} for g in x["gold"]],
            "judgment_origin": JUDGMENT_ORIGIN[split], "pooling": POOLING[split],
            "independent_of_tested_policy": True, "task_types": tag_task_types(x["question"], tag_sources)})

    # sources, grouped by family
    ps = prov["statute"]
    for sid in sorted(statute):
        s = statute[sid]
        if s["law_code"] in heldout_laws:
            split, fid = "heldout", ho_fam[s["law_code"]]
        else:
            split, fid = "dev", dev_fam[s["law_code"]]
        out[split]["sources"].append({
            "source_id": sid, "packet_id": fid, "law_code": s["law_code"], "law_name": s["law_name"],
            "section_num": s["section_num"], "text": s["text"], "text_sha256": sha256_text(s["text"]),
            "cross_references": s["references"], "source_origin": "real_statute_section",
            "provenance": {"dataset": ps["repo"], "revision": ps["revision"], "license": ps["license"],
                           "file": ps["file"], "locator": f"statute_ccl/{s['law_code']}/{s['section_num']}"}})
    for sid in sorted(extra_sources):
        s = extra_sources[sid]
        out["dev"]["sources"].append({
            "source_id": sid, "packet_id": s["packet_id"], "law_code": s["law_code"], "law_name": None,
            "section_num": s["section_num"], "text": s["text"], "text_sha256": sha256_text(s["text"]),
            "cross_references": [], "source_origin": "real_statute_text_from_wangchanx_positive_context",
            "provenance": {"dataset": pw["repo"], "revision": pw["revision"], "license": pw["license"],
                           "file": pw["file"], "locator": "positive_contexts (not in the statute corpus)"}})

    for split in ("dev", "heldout"):
        packets = collections.OrderedDict()
        for s in out[split]["sources"]:
            packets.setdefault(s["packet_id"], {"laws": set(), "sources": [], "items": []})
            packets[s["packet_id"]]["laws"].add(s["law_code"])
            packets[s["packet_id"]]["sources"].append(s["source_id"])
        for r in out[split]["requests"]:
            packets.setdefault(r["packet_id"], {"laws": set(), "sources": [], "items": []})
            packets[r["packet_id"]]["items"].append(r["item_id"])
        fam = dev_fam if split == "dev" else ho_fam
        for law, fid in fam.items():
            if fid in packets:
                packets[fid]["laws"].add(law)
        out[split]["packets"] = [{"packet_id": fid, "split": split, "laws": sorted(v["laws"]),
                                  "n_sources": len(v["sources"]), "n_items": len(v["items"]),
                                  "source_ids": v["sources"], "item_ids": v["items"]}
                                 for fid, v in sorted(packets.items())]

    # ------------------------------------------------------------------ invariants
    dev_laws = {law for pk in out["dev"]["packets"] for law in pk["laws"]}
    ho_laws = {law for pk in out["heldout"]["packets"] for law in pk["laws"]}
    dev_sources = {s["source_id"] for s in out["dev"]["sources"]}
    ho_sources = {s["source_id"] for s in out["heldout"]["sources"]}
    dev_judged = {g["source_id"] for j in out["dev"]["judgments"] for g in j["relevant"]} | \
                 {sid for j in out["dev"]["judgments"] for sid in j["judged_nonrelevant"]}
    dev_hashes = {x["hash"] for x in dev}
    dev_hmax = max([heldout_max[i] for i, x in enumerate(wx) if x["hash"] in dev_hashes] or [0.0])
    checks = {
        "no_law_in_both_splits": not (dev_laws & ho_laws),
        "no_source_in_both_splits": not (dev_sources & ho_sources),
        "no_dev_judgment_on_heldout_source": not (dev_judged & ho_sources),
        "no_dev_question_equals_heldout_normalised": not ({x["norm"] for x in dev} & heldout_norm),
        "dev_max_jaccard_to_heldout_below_threshold": dev_hmax < thr,
        "every_item_in_one_packet": len({r["item_id"] for s in ("dev", "heldout") for r in out[s]["requests"]})
        == len(out["dev"]["requests"]) + len(out["heldout"]["requests"]),
    }
    if not all(checks.values()):
        raise AssertionError(f"split invariant failed: {checks}")

    counts = summarise(out, reasons, dropped_neg, len(wx), len(heldout_items), len(gz_raw))
    counts["heldout_laws"] = {"total": len(heldout_laws), "from_reference_laws_only": len(ref_only_laws),
                              "unmapped_law_name_mentions": unmapped_mentions}
    counts["dev_max_jaccard_to_heldout"] = round(dev_hmax, 4)
    audit["dev_after_split"] = {"n_dev": len(dev), "max_jaccard_to_any_heldout_question": round(dev_hmax, 4),
                                f"dev_internal_variant_pairs_{thr}": len(dev_pairs)}
    return {"splits": {s: dict(v) for s, v in out.items()}, "excluded": sorted(excluded, key=lambda e: e["record_id_hash"]),
            "audit": audit, "counts": counts, "checks": checks}


def summarise(out, reasons, dropped_neg, n_wx, n_heldout, n_gazette) -> dict:
    c = {"inputs": {"wangchanx_train_records": n_wx, "nitibench_heldout_records": n_heldout,
                    "gazette_queries_audit_only": n_gazette},
         "dev_exclusions": dict(sorted(reasons.items())), "dev_hard_negatives_dropped_heldout_law": dropped_neg}
    for split in ("dev", "heldout"):
        sp = out[split]
        by_source = collections.Counter(r["provenance"]["dataset"] + ":" + r["provenance"]["locator"].split("[")[0]
                                        for r in sp["requests"])
        labels = collections.Counter(r["synthetic_label"] for r in sp["requests"])
        any_cue = collections.Counter()
        q_cue = collections.Counter()
        combos = collections.Counter()
        for j in sp["judgments"]:
            tt = j["task_types"]
            combos["+".join(sorted(tt))] += 1
            for t, basis in tt.items():
                any_cue[t] += 1
                if "question" in basis:
                    q_cue[t] += 1
        sizes = sorted((pk["n_items"] for pk in sp["packets"]), reverse=True)
        c[split] = {
            "items": len(sp["requests"]), "packets": len(sp["packets"]),
            "packets_with_items": sum(1 for s in sizes if s), "laws": len({l for pk in sp["packets"] for l in pk["laws"]}),
            "sources": len(sp["sources"]),
            "sources_not_in_statute_corpus": sum(1 for s in sp["sources"]
                                                 if s["source_origin"] != "real_statute_section"),
            "items_by_source": dict(sorted(by_source.items())), "items_by_synthetic_label": dict(sorted(labels.items())),
            "task_type_any_cue": {t: any_cue.get(t, 0) for t in TASK_TYPES},
            "task_type_question_cue": {t: q_cue.get(t, 0) for t in TASK_TYPES if t != "plain"},
            "task_type_combinations": dict(sorted(combos.items())),
            "packet_item_counts_desc": sizes,
            "relevant_per_item": dict(sorted(collections.Counter(len(j["relevant"]) for j in sp["judgments"]).items())),
            "relevant_not_in_statute_corpus": sum(1 for j in sp["judgments"] for g in j["relevant"]
                                                  if not g["in_statute_corpus"]),
        }
    return c



def sha256_text(text) -> str:
    return hashlib.sha256((text or "").encode("utf-8")).hexdigest()


def record_hash(repo, revision, locator) -> str:
    return sha256_text(f"{repo}@{revision}:{locator}")


# --------------------------------------------------------------------------- near-duplicates

def shingles(text: str, k: int) -> frozenset:
    if not text:
        return frozenset()
    if len(text) <= k:
        return frozenset([text])
    return frozenset(text[i:i + k] for i in range(len(text) - k + 1))


def _csr(sets, vocab):
    import numpy as np
    import scipy.sparse as sp
    indptr, indices = [0], []
    for s in sets:
        indices.extend(sorted(vocab[x] for x in s))
        indptr.append(len(indices))
    return sp.csr_matrix((np.ones(len(indices), dtype=np.float32), np.array(indices, dtype=np.int64),
                          np.array(indptr, dtype=np.int64)), shape=(len(sets), max(len(vocab), 1)))


def jaccard_scan(a_sets, b_sets=None, *, pair_threshold=None, block=1024):
    """Max Jaccard of every a against b (and every b against a), argmax for b, and pairs >= pair_threshold.

    With ``b_sets=None`` a is compared with itself: the diagonal is ignored and pairs are reported once (i < j)."""
    import numpy as np
    same = b_sets is None
    if same:
        b_sets = a_sets
    vocab = {}
    for s in list(a_sets) + ([] if same else list(b_sets)):
        for x in s:
            if x not in vocab:
                vocab[x] = len(vocab)
    a_max = np.zeros(len(a_sets), dtype=np.float64)
    b_max = np.zeros(len(b_sets), dtype=np.float64)
    b_arg = np.full(len(b_sets), -1, dtype=np.int64)
    pairs = []
    if not a_sets or not b_sets:
        return a_max, b_max, b_arg, pairs
    A = _csr(a_sets, vocab)
    B = A if same else _csr(b_sets, vocab)
    sa = np.array([len(s) for s in a_sets], dtype=np.float64)
    sb = np.array([len(s) for s in b_sets], dtype=np.float64)
    for start in range(0, len(b_sets), block):
        stop = min(start + block, len(b_sets))
        inter = (A @ B[start:stop].T).toarray().astype(np.float64)
        union = sa[:, None] + sb[None, start:stop] - inter
        with np.errstate(divide="ignore", invalid="ignore"):
            jac = np.where(union > 0, inter / union, 0.0)
        if same:
            cols = np.arange(start, stop)
            jac[cols, cols - start] = 0.0
        a_max = np.maximum(a_max, jac.max(axis=1))
        b_max[start:stop] = jac.max(axis=0)
        b_arg[start:stop] = jac.argmax(axis=0)
        if pair_threshold is not None:
            ii, jj = np.nonzero(jac >= pair_threshold)
            for i, j in zip(ii.tolist(), (jj + start).tolist()):
                if not same or i < j:
                    pairs.append((i, j))
    b_arg[b_max <= 0] = -1
    return a_max, b_max, b_arg, sorted(pairs)


def _quantiles(values):
    import numpy as np
    if len(values) == 0:
        return {}
    q = np.percentile(np.asarray(values), [50, 90, 99, 100])
    return {"p50": round(float(q[0]), 4), "p90": round(float(q[1]), 4), "p99": round(float(q[2]), 4),
            "max": round(float(q[3]), 4)}


def question_overlap(a_raw, b_raw, a_norm, b_norm, a_sh, b_sh, thresholds):
    """Aggregate question overlap of set a (DEV candidate pool) against set b (a held-out set)."""
    a_max, b_max, b_arg, _ = jaccard_scan(a_sh, b_sh)
    raw_a, raw_b, norm_a, norm_b = set(a_raw), set(b_raw), set(a_norm) - {""}, set(b_norm) - {""}
    out = {
        "n_a": len(a_raw), "n_b": len(b_raw),
        "exact": {"a_in_b": sum(1 for x in a_raw if x in raw_b), "b_in_a": sum(1 for x in b_raw if x in raw_a)},
        "normalised": {"a_in_b": sum(1 for x in a_norm if x and x in norm_b),
                       "b_in_a": sum(1 for x in b_norm if x and x in norm_a)},
        "near_dup": {str(t): {"a_with_match": int((a_max >= t).sum()), "b_with_match": int((b_max >= t).sum())}
                     for t in thresholds},
        "b_max_jaccard": _quantiles(b_max),
    }
    return out, a_max, b_max, b_arg


# --------------------------------------------------------------------------- task types

def tag_task_types(question, sources, rules=None) -> dict:
    """sources: list of dicts with ``id_section`` (normalised section part), ``text`` and ``has_reference`` (bool).

    Returns {task_type: sorted basis list}; ``{"plain": ["no_cue"]}`` when nothing fired."""
    rules = TASK_RULES if rules is None else rules
    q = light_norm(question)
    tags = {}
    for ttype, rule in rules.items():
        basis = set()
        if rule.get("question") and re.search(rule["question"], q):
            basis.add("question")
        for s in sources:
            if rule.get("source_text") and re.search(rule["source_text"], light_norm(s.get("text"))):
                basis.add("source_text")
            if rule.get("source_reference") and s.get("has_reference"):
                basis.add("source_reference")
            if rule.get("source_id_non_section") and not _SECTION_ID.match(s.get("id_section") or ""):
                basis.add("source_id")
        if basis:
            tags[ttype] = sorted(basis)
    return tags or {"plain": ["no_cue"]}


# --------------------------------------------------------------------------- families

class UnionFind:
    def __init__(self):
        self.parent = {}

    def add(self, x):
        self.parent.setdefault(x, x)

    def find(self, x):
        self.add(x)
        root = x
        while self.parent[root] != root:
            root = self.parent[root]
        while self.parent[x] != root:
            self.parent[x], x = root, self.parent[x]
        return root

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            if rb < ra:
                ra, rb = rb, ra
            self.parent[rb] = ra


def law_family(split: str, law_code: str) -> str:
    """Deterministic family (packet) id for one law within one split."""
    return f"{split}-" + sha256_text(law_code)[:12]


def component_sizes(item_laws, laws) -> dict:
    """Connected components of laws linked by items citing several laws: item counts per component (descending)."""
    uf = UnionFind()
    for law in laws:
        uf.add(law)
    for ls in item_laws:
        for law in ls[1:]:
            uf.union(ls[0], law)
    sizes = collections.Counter(uf.find(ls[0]) for ls in item_laws if ls)
    return {"components": len({uf.find(law) for law in uf.parent}),
            "items_per_component_desc": sorted(sizes.values(), reverse=True)}



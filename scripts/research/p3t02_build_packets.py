def _sha256_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def resolve_inputs(data_dir: pathlib.Path) -> dict:
    manifest = json.loads((data_dir / "MANIFEST.json").read_text(encoding="utf-8"))
    found = {}
    for key, (repo, rel) in INPUTS.items():
        ds = next(d for d in manifest["datasets"] if d["repo"] == repo)
        entry = next(f for f in ds["files"] if f["path"] == rel)
        path = data_dir / f"{repo.split('/')[1]}@{ds['revision'][:8]}" / rel
        actual = _sha256_file(path)
        if actual != entry["sha256"]:
            raise SystemExit(f"sha256 mismatch for {repo}/{rel}")
        found[key] = {"repo": repo, "revision": ds["revision"], "license": ds["license"], "file": rel,
                      "role": entry["role"], "sha256": actual, "path": path}
    return found


def read_rows(inputs: dict) -> dict:
    import pyarrow.parquet as pq
    rows = {}
    for key, cols in COLUMNS.items():
        table = pq.read_table(inputs[key]["path"], columns=cols)
        rows[key] = table.column(0).to_pylist() if key == "gazette_queries" else table.to_pylist()
    return rows


def _write_jsonl(path: pathlib.Path, records) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n")


def assert_aggregate_only(obj) -> None:
    """Refuse a Git-bound summary that contains Thai text (questions, law names or Thai law codes)."""
    text = json.dumps(obj, ensure_ascii=False)
    if _THAI_CHAR.search(text):
        raise ValueError("summary contains Thai characters: not aggregate-only")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--data", required=True, type=pathlib.Path)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("--extra-site", type=pathlib.Path, help="site-packages holding pythainlp (appended to sys.path)")
    ap.add_argument("--summary-out", type=pathlib.Path)
    ap.add_argument("--allow-no-pythainlp", action="store_true")
    ap.add_argument("--overwrite", action="store_true")
    args = ap.parse_args(argv)

    if args.extra_site:
        sys.path.append(str(args.extra_site))
    thai_normalize, pythainlp_version = load_thai_normalizer()
    if thai_normalize is None and not args.allow_no_pythainlp:
        raise SystemExit("pythainlp not importable; pass --extra-site or --allow-no-pythainlp")
    if args.out.exists() and any(args.out.iterdir()) and not args.overwrite:
        raise SystemExit(f"{args.out} exists and is not empty (one settle per job; use --overwrite deliberately)")

    inputs = resolve_inputs(args.data)
    rows = read_rows(inputs)
    prov = {k: {x: v[x] for x in ("repo", "revision", "license", "file")} for k, v in inputs.items()}
    result = build(rows, prov, thai_normalize)

    out = args.out
    outputs = {}
    for split in ("dev", "heldout"):
        for name, recs in sorted(result["splits"][split].items()):
            fname = "judgments.SEALED.jsonl" if (split == "heldout" and name == "judgments") else f"{name}.jsonl"
            path = out / split / fname
            _write_jsonl(path, recs)
            outputs[f"{split}/{fname}"] = len(recs)
    _write_jsonl(out / "excluded.jsonl", result["excluded"])
    outputs["excluded.jsonl"] = len(result["excluded"])
    (out / "overlap_audit.json").write_text(json.dumps(result["audit"], indent=1, sort_keys=True) + "\n",
                                            encoding="utf-8", newline="\n")
    outputs["overlap_audit.json"] = None
    hashes = {rel: _sha256_file(out / rel) for rel in sorted(outputs)}

    import numpy
    import scipy
    script = pathlib.Path(__file__).resolve()
    manifest = {
        "builder": BUILDER_VERSION, "builder_sha256": _sha256_file(script), "task": "P3-T02",
        "built_utc": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat(),
        "python": platform.python_version(), "pythainlp": pythainlp_version, "numpy": numpy.__version__,
        "scipy": scipy.__version__, "declared": DECLARED, "task_rules": TASK_RULES,
        "inputs": {k: {x: v[x] for x in ("repo", "revision", "license", "file", "role", "sha256")}
                   for k, v in inputs.items()},
        "outputs": {rel: {"sha256": hashes[rel], "records": outputs[rel]} for rel in sorted(outputs)},
        "counts": result["counts"], "checks": result["checks"],
        "access_note": ("heldout/judgments.SEALED.jsonl is evaluator-only: open it only to score a frozen method. "
                        "Runtime inputs are requests.jsonl and sources.jsonl."),
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n",
                                       encoding="utf-8", newline="\n")
    hashes["MANIFEST.json"] = _sha256_file(out / "MANIFEST.json")
    (out / "SHA256SUMS").write_text("".join(f"{h}  {rel}\n" for rel, h in sorted(hashes.items())),
                                    encoding="utf-8", newline="\n")

    if args.summary_out:
        summary = {
            "task": "P3-T02", "builder": BUILDER_VERSION, "builder_sha256": manifest["builder_sha256"],
            "pythainlp": pythainlp_version, "declared": DECLARED,
            "inputs": {k: {x: v[x] for x in ("repo", "revision", "license", "file", "role", "sha256")}
                       for k, v in inputs.items()},
            "outputs_sha256": hashes, "counts": result["counts"], "checks": result["checks"],
            "overlap_audit": {k: v for k, v in result["audit"].items() if k != "declared"},
        }
        assert_aggregate_only(summary)
        args.summary_out.write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n", encoding="utf-8",
                                    newline="\n")
    print(json.dumps({"out": str(out), "checks": result["checks"], "dev_items": result["counts"]["dev"]["items"],
                      "heldout_items": result["counts"]["heldout"]["items"]}))
    return 0



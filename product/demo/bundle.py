"""Bundle the demo data into data.bundle.js so the app runs from file://.

Browsers block fetch() for file:// pages. This script reads the index manifest
(data/index.json, or fixtures/index.json when PRD1 data is absent), inlines the
index and every queue and dossier it references, and writes

    window.MWD_DATA = {"base": "...", "index": {...}, "files": {"<path>": {...}}};

PRD1 writes queue-*.json and dossier-*.json into data/ without an index, so for
data/ the script first writes data/index.json from those files (schema mwd.index.v1).

The current queue (data/current/, Track A t0 forecast) is bundled separately into
data.current.bundle.js as window.MWD_CURRENT, so the app loads it only in the Current queue mode:

    python product/demo/bundle.py --current

Run from anywhere:  python product/demo/bundle.py [--source data|fixtures] [--current]
Standard library only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def write_data_index(base: Path) -> None:
    """Index PRD1 output (mwd.queue.v1 / mwd.dossier.v1 files) for the app."""
    queues, dossiers = [], []
    for path in sorted(base.glob("queue-*.json")):
        q = json.loads(path.read_text(encoding="utf-8"))
        queues.append({"cutoff": q["as_of"][:4], "as_of": q["as_of"], "horizon_months": q["horizon_months"],
                       "path": path.name})
    for path in sorted(base.glob("dossier-*.json")):
        d = json.loads(path.read_text(encoding="utf-8"))
        dossiers.append({"key": d["molecule"]["key"], "display_name": d["molecule"]["display_name"],
                         "cutoff": d["as_of"][:4], "as_of": d["as_of"],
                         "horizon_months": d["forecast"]["horizon_months"], "path": path.name})
    index = {"schema": "mwd.index.v1", "fixture": False, "status": "DEVELOPMENT_ONLY",
             "note": "Development data: cutoffs before 2017. Built by product/mwd (PRD1).",
             "jurisdiction": "US", "queues": queues, "dossiers": dossiers}
    (base / "index.json").write_text(json.dumps(index, ensure_ascii=False, indent=2) + "\n",
                                     encoding="utf-8", newline="\n")


def bundle_current() -> int:
    """Write data.current.bundle.js from data/current/index.json (window.MWD_CURRENT)."""
    base = HERE / "data" / "current"
    index_path = base / "index.json"
    if not index_path.exists():
        print(f"error: {index_path} not found", file=sys.stderr)
        return 1
    index = json.loads(index_path.read_text(encoding="utf-8"))
    files: dict[str, object] = {}
    for entry in index["queues"] + index["dossiers"]:
        files[entry["path"]] = json.loads((base / entry["path"]).read_text(encoding="utf-8"))
    payload = {"base": "current", "index": index, "files": files}
    text = ("/* Generated by product/demo/bundle.py --current from data/current/index.json. Do not edit. */" + chr(10) +
            "window.MWD_CURRENT = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";" + chr(10))
    out = HERE / "data.current.bundle.js"
    out.write_bytes(text.encode("utf-8"))
    print(f"bundled {len(files)} files from data/current/ into {out} ({len(text.encode('utf-8')):,} bytes)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--current", action="store_true", help="bundle data/current/ into data.current.bundle.js")
    ap.add_argument("--source", choices=["data", "fixtures"], help="default: data if data/index.json exists")
    ap.add_argument("--out", default=str(HERE / "data.bundle.js"))
    args = ap.parse_args()
    if args.current:
        return bundle_current()

    has_data = any((HERE / "data").glob("dossier-*.json"))
    source = args.source or ("data" if has_data else "fixtures")
    base = HERE / source
    if source == "data":
        write_data_index(base)
    index_path = base / "index.json"
    if not index_path.exists():
        print(f"error: {index_path} not found", file=sys.stderr)
        return 1
    index = json.loads(index_path.read_text(encoding="utf-8"))

    files: dict[str, object] = {}
    missing = []
    for entry in index.get("queues", []) + index.get("dossiers", []):
        rel = entry["path"]
        path = base / rel
        if not path.exists():
            missing.append(rel)
            continue
        files[rel] = json.loads(path.read_text(encoding="utf-8"))
    if missing:
        print(f"warning: {len(missing)} referenced files missing, e.g. {missing[0]}", file=sys.stderr)

    payload = {"base": source, "index": index, "files": files}
    text = ("/* Generated by product/demo/bundle.py from " + source + "/index.json. Do not edit. */\n"
            "window.MWD_DATA = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n")
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"bundled {len(files)} files from {source}/ into {args.out} ({len(text.encode('utf-8')):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Write assets/fonts/fonts.css for the app and the landing page, with the woff2 files inlined.

Browsers refuse web fonts loaded from file:// pages, so the app (which must open from a file and
inside the Tauri window) carries the self-hosted fonts as data: URIs. The woff2 files beside the
CSS are the sources; see docs/loe-bench/receipts/UIBUILD.md for their origin, licence and SHA-256.
Run from anywhere:  python product/demo/fonts_css.py   (standard library only)
"""

import base64
from pathlib import Path

PRODUCT = Path(__file__).resolve().parents[1]
FACES = [
    ("Source Sans 3", "200 900", "source-sans-3-latin-wght-normal.woff2",
     "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, "
     "U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD"),
    ("Source Sans 3", "200 900", "source-sans-3-latin-ext-wght-normal.woff2",
     "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+1D00-1DBF, U+1E00-1E9F, "
     "U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C4, U+2113, U+2C60-2C7F, U+A720-A7FF"),
    ("Noto Sans Thai", "100 900", "noto-sans-thai-thai-wght-normal.woff2",
     "U+02D7, U+0303, U+0331, U+0E01-0E5B, U+200C-200D, U+25CC"),
]


def main():
    for app in ("demo", "site"):
        folder = PRODUCT / app / "assets" / "fonts"
        parts = ["/* Generated by product/demo/fonts_css.py. Fonts: SIL Open Font License 1.1 (see OFL-*.txt). */"]
        for family, weight, file, ranges in FACES:
            data = base64.b64encode((folder / file).read_bytes()).decode("ascii")
            parts.append("@font-face {\n  font-family: \"%s\";\n  font-style: normal;\n  font-weight: %s;\n"
                         "  font-display: swap;\n  src: url(data:font/woff2;base64,%s) format(\"woff2\");\n"
                         "  unicode-range: %s;\n}" % (family, weight, data, ranges))
        (folder / "fonts.css").write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
        print("wrote", folder / "fonts.css")


if __name__ == "__main__":
    main()
